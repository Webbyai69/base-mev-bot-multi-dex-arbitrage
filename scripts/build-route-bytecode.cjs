/**
 * Compiles contracts/RouteExecutor.sol and writes its runtime bytecode to
 * src/simBytecodeRoute.ts, so the bot can simulate multi-hop routes exactly
 * (real pools, real token transfers, real flash loan) through an eth_call
 * state override — no deployment and no private key needed.
 *
 * Needs the solc 0.8 compiler from npm (one-off, not saved to package.json):
 *   npm install --no-save solc@0.8.26
 *   node scripts/build-route-bytecode.cjs
 *   npm run build
 *
 * Also prints the ABI-encoded deployment bytecode size and writes
 * build/RouteExecutor.json (abi + bytecode) for deploying with Remix/Foundry.
 */
const fs = require("node:fs");
const path = require("node:path");

let solc;
try {
  solc = require("solc");
} catch {
  console.error("solc is not installed. Run:  npm install --no-save solc@0.8.26");
  process.exit(1);
}

const root = path.join(__dirname, "..");
const source = fs.readFileSync(path.join(root, "contracts", "RouteExecutor.sol"), "utf8");
const input = {
  language: "Solidity",
  sources: { "RouteExecutor.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 1000 },
    evmVersion: "cancun",
    outputSelection: { "*": { RouteExecutor: ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors || []).filter((e) => e.severity === "error");
for (const e of out.errors || []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);

const c = out.contracts["RouteExecutor.sol"].RouteExecutor;
const runtime = "0x" + c.evm.deployedBytecode.object;
const ts = `/**
 * RouteExecutor runtime bytecode for eth_call state-override simulation.
 * Generated by scripts/build-route-bytecode.cjs with solc ${solc.version()} — do not edit by hand; rebuild after changing the contract.
 */
export const ROUTE_EXECUTOR_RUNTIME = "${runtime}";
`;
fs.writeFileSync(path.join(root, "src", "simBytecodeRoute.ts"), ts);
const creation = "0x" + c.evm.bytecode.object;
fs.writeFileSync(
  path.join(root, "src", "deployBytecode.ts"),
  `/**
 * RouteExecutor creation bytecode, used by the dashboard's "Deploy" button: your
 * wallet sends it as a contract-creation transaction and becomes the contract's owner.
 * Generated by scripts/build-route-bytecode.cjs with solc ${solc.version()}, together with src/simBytecodeRoute.ts.
 */
export const ROUTE_EXECUTOR_CREATION = "${creation}";
export const ROUTE_EXECUTOR_COMPILER = "solc ${solc.version()}, optimizer 1000 runs, evm cancun";
`,
);
fs.mkdirSync(path.join(root, "build"), { recursive: true });
fs.writeFileSync(path.join(root, "build", "RouteExecutor.json"), JSON.stringify({ abi: c.abi, bytecode: "0x" + c.evm.bytecode.object }, null, 2));
console.log(`RouteExecutor compiled with solc ${solc.version()}: runtime ${(runtime.length - 2) / 2} bytes`);
console.log("wrote src/simBytecodeRoute.ts, src/deployBytecode.ts and build/RouteExecutor.json — now run: npm run build");
