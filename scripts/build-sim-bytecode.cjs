/**
 * Builds the runtime bytecode used for eth_call *state-override* simulation:
 * the bot injects ArbExecutor's code at an address that does not exist and
 * calls simulate(), which reverts with Simulated(profit). No deployment, no
 * private key, and the answer comes from the real pools with real transfers.
 *
 * The compiler shipped with any Hardhat 2.x project (solc 0.7.3 in
 * node_modules/solc) can be used: this script down-converts the 0.8 source
 * (custom errors -> require strings) and hand-encodes the two custom errors
 * the bot decodes, so the revert data matches the 0.8 ABI exactly.
 *
 *   SOLC_NODE_MODULES=<path to a node_modules containing solc> node scripts/build-sim-bytecode.cjs
 */
const fs = require("node:fs");
const path = require("node:path");

const NM = process.env.SOLC_NODE_MODULES;
if (!NM) {
  console.error("set SOLC_NODE_MODULES to a node_modules directory that contains solc");
  process.exit(1);
}
const solc = require(path.join(NM, "solc"));
const root = path.join(__dirname, "..");
const src = fs.readFileSync(path.join(root, "contracts", "ArbExecutor.sol"), "utf8");

const SIMULATED = "0x6f149831"; // Simulated(uint256)
const INSUFFICIENT = "0x4e88422a"; // InsufficientProfit(uint256,uint256)

const down = src
  .replace("pragma solidity ^0.8.20;", "pragma solidity ^0.7.3;")
  .replace(/\n {4}error [A-Za-z]+\([^)]*\);/g, "")
  .replace("if (msg.sender != owner) revert NotOwner();", 'require(msg.sender == owner, "NotOwner");')
  .replace(/if \(profit < minProfit\) revert InsufficientProfit\(profit, minProfit\);/g,
    `if (profit < minProfit) { assembly { mstore(0, shl(224, ${INSUFFICIENT})) mstore(4, profit) mstore(36, minProfit) revert(0, 68) } }`)
  .replace("revert Simulated(profit);", `assembly { mstore(0, shl(224, ${SIMULATED})) mstore(4, profit) revert(0, 36) }`)
  .replace(/if \(after_ <= before\) revert InsufficientProfit\(0, 1\);/g,
    `if (after_ <= before) { assembly { mstore(0, shl(224, ${INSUFFICIENT})) mstore(4, 0) mstore(36, 1) revert(0, 68) } }`)
  .replace("if (msg.sender != expectedCaller || sender != address(this)) revert BadCallback();", 'require(msg.sender == expectedCaller && sender == address(this), "BadCallback");')
  .replace("if (!ok || (ret.length != 0 && !abi.decode(ret, (bool)))) revert TransferFailed();", 'require(ok && (ret.length == 0 || abi.decode(ret, (bool))), "TransferFailed");')
  .replace("if (msg.data.length < 4 + 32 * 4) revert BadCallback();", 'require(msg.data.length >= 4 + 32 * 4, "BadCallback");')
  .replace("if (!ok) revert TransferFailed();", 'require(ok, "TransferFailed");');

if (down.includes("revert Simulated") || down.includes("revert InsufficientProfit") || /\berror\s+[A-Z]/.test(down)) {
  console.error("down-conversion incomplete; the contract source changed shape");
  process.exit(1);
}

const input = {
  language: "Solidity",
  sources: { "ArbExecutor.sol": { content: down } },
  settings: { optimizer: { enabled: true, runs: 200 }, outputSelection: { "*": { "*": ["evm.deployedBytecode.object", "abi"] } } },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e) => e.severity === "error");
if (errors.length) {
  console.error(errors.map((e) => e.formattedMessage).join("\n"));
  process.exit(1);
}
const runtime = "0x" + out.contracts["ArbExecutor.sol"].ArbExecutor.evm.deployedBytecode.object;
const file = path.join(root, "src", "simBytecode.ts");
fs.writeFileSync(
  file,
  `/**
 * ArbExecutor runtime bytecode for eth_call state-override simulation.
 * Generated by scripts/build-sim-bytecode.cjs from contracts/ArbExecutor.sol
 * with solc ${solc.version()} — do not edit by hand; rebuild after changing the contract.
 */
export const SIM_EXECUTOR_RUNTIME = "${runtime}";
export const SIM_EXECUTOR_BYTES = ${(runtime.length - 2) / 2};
`,
);
console.log(`wrote ${file}: ${(runtime.length - 2) / 2} bytes of runtime code (solc ${solc.version()})`);
